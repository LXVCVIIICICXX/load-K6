/* Адрес стенда и пользователи — единственное, что меняется от площадки к площадке.
 *
 * Раньше они лежали в каждом сценарии значением по умолчанию, и файл нельзя
 * было показать никому за пределами проекта. Теперь всё приходит снаружи:
 * из .env через run.py (или через `k6 run --env`), а сценарии не знают ни
 * одного адреса и ни одного пароля.
 */

// Падать сразу и по-русски: k6 иначе уйдёт бить пустой URL и покажет
// невнятную ошибку сети на каждой итерации.
export function need(name) {
  const v = __ENV[name];
  if (!v) throw new Error(
    `не задана переменная ${name}: заполни .env (см. .env.example) или передай --env ${name}=…`);
  return v;
}

export const API  = need('API_URL').replace(/\/+$/, '');
// Фронт живёт на том же домене без префикса api. — но стенды бывают разные,
// поэтому SITE_URL при необходимости задаётся отдельно.
export const SITE = (__ENV.SITE_URL || API.replace('://api.', '://')).replace(/\/+$/, '');

/* Пара логин-пароль для роли. Роль — метка, которую вы придумали сами
   (student, admin, buyer); из неё складывается имя переменных:
   creds('student') → STUDENT_EMAIL и STUDENT_PASS.

   Вызывать в init-секции — тогда о незаполненном профиле узнаешь до старта,
   а не на первой итерации. */
export function creds(role) {
  const p = String(role || '').toUpperCase().replace(/[^A-Z0-9]+/g, '_').replace(/^_+|_+$/g, '');
  if (!p) throw new Error('не сказано, какой ролью ходить: задай ROLE (см. .env.example)');
  return { email: need(p + '_EMAIL'), password: need(p + '_PASS') };
}
